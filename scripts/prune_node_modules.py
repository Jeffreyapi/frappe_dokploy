"""Materialize minimal runtime slices; retain complete build dependencies in the bench."""

import argparse
import json
import re
import shutil
from pathlib import Path

SERVER_ROOTS = {"frappe": ["socket.io", "@redis/client", "cookie"]}
ASSET_ROOTS = {"frappe": ["photoswipe", "qz-tray", "js-sha256", "html5-qrcode", "frappe-gantt", "ace-builds"]}
PACKAGE = re.compile(r"(?:@[a-zA-Z0-9._-]+/)?[a-zA-Z0-9._-]+\Z")


def package_path(name):
    if not PACKAGE.fullmatch(name) or any(part in {".", ".."} for part in name.split("/")):
        raise ValueError(f"Invalid runtime package: {name}")
    return Path(name)


def resolve_package(root, name, requester=None):
    relative = package_path(name)
    current = requester if requester is not None else root.parent
    while current == root.parent or root.parent in current.parents:
        candidate = current / "node_modules" / relative
        if (candidate / "package.json").is_file():
            if not candidate.resolve().is_relative_to(root.resolve()):
                raise ValueError(f"Package escapes node_modules: {name}")
            return candidate
        if current == root.parent:
            break
        current = current.parent
    return None


def closure(root, names):
    pending = []
    for name in names:
        path = resolve_package(root, name)
        if path is None:
            raise ValueError(f"Missing runtime root package: {name}")
        pending.append(path)
    found = set()
    while pending:
        package = pending.pop()
        if package in found:
            continue
        found.add(package)
        metadata = json.loads((package / "package.json").read_text(encoding="utf-8"))
        optional = metadata.get("optionalDependencies", {})
        dependencies = {**metadata.get("dependencies", {}), **optional}
        for name in dependencies:
            dependency = resolve_package(root, name, package)
            if dependency is None:
                if name not in optional:
                    raise ValueError(f"Missing dependency {name} of {package.name}")
            else:
                pending.append(dependency)
        # Peer dependencies are supplied by the parent package tree, when installed.
        for name in metadata.get("peerDependencies", {}):
            dependency = resolve_package(root, name, package)
            if dependency is not None:
                pending.append(dependency)
    return sorted(found)


def materialize(root, names, destination):
    if destination.resolve().is_relative_to(root.resolve()) or root.resolve().is_relative_to(destination.resolve()):
        raise ValueError("Runtime slice must not overlap build node_modules")
    packages = closure(root, names)
    if destination.exists():
        shutil.rmtree(destination)
    destination.mkdir(parents=True)
    for package in packages:
        target = destination / package.relative_to(root)
        target.parent.mkdir(parents=True, exist_ok=True)
        # Nested node_modules are copied separately from their selected closure.
        shutil.copytree(package, target, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns("node_modules"), symlinks=False)
    return [str(package.relative_to(root)) for package in packages]


def build_slice(bench, app, output):
    if not re.fullmatch(r"[a-z][a-z0-9_]*", app):
        raise ValueError("Invalid app name")
    app_dir = bench / "apps" / app
    roots = {"server": list(SERVER_ROOTS.get(app, [])), "assets": list(ASSET_ROOTS.get(app, []))}
    declaration = app_dir / "runtime-node-modules.txt"
    if declaration.exists():
        for raw in declaration.read_text(encoding="utf-8").splitlines():
            line = raw.split("#", 1)[0].strip()
            if not line:
                continue
            kind, sep, name = line.partition(":")
            if not sep:
                kind, name = "both", line
            name = name.strip()
            package_path(name)
            if kind not in {"server", "assets", "both"}:
                raise ValueError("Use server:, assets: or a bare package name")
            for scope, packages in roots.items():
                if kind in {scope, "both"}:
                    packages.append(name)
    root = app_dir / "node_modules"
    result = {}
    for scope, directory in (("server", "node_modules"), ("assets", "assets-node_modules")):
        result[scope] = materialize(root, roots[scope], output / app / directory)
    (output / app / "manifest.json").write_text(json.dumps(result, sort_keys=True) + "\n", encoding="utf-8")
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--bench", type=Path, required=True)
    parser.add_argument("--app", required=True)
    parser.add_argument("--output", type=Path, default=Path("/opt/runtime-slice"))
    args = parser.parse_args()
    build_slice(args.bench, args.app, args.output)


if __name__ == "__main__":
    main()
